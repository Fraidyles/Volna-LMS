// Порядок в тесте урока: исходные вопросы с одним верным ответом чередуются с
// новыми типами, чтобы тест не начинался с одинаковых вопросов подряд.
function mergeLessonQuiz(base, extra){
  const byLesson = new Map();
  extra.forEach((q) => { if (!byLesson.has(q.lessonId)) byLesson.set(q.lessonId, []); byLesson.get(q.lessonId).push(q); });
  const out = [], done = new Set();
  base.forEach((q) => {
    if (!q.lessonId) { out.push(q); return; }
    if (done.has(q.lessonId)) return;
    done.add(q.lessonId);
    const own = base.filter((x) => x.lessonId === q.lessonId), add = byLesson.get(q.lessonId) || [];
    for (let i = 0; i < Math.max(own.length, add.length); i++) {
      if (own[i]) out.push(own[i]);
      if (add[i]) out.push(add[i]);
    }
  });
  return out;
}

